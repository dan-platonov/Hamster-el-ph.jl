function parse_arguments(args)
    settings = Dict{Symbol,Any}(
        :start => DEFAULT_START_SNAPSHOT,
        :final => DEFAULT_FINAL_SNAPSHOT,
        :skip_snapshots => DEFAULT_SKIP_SNAPSHOTS,
        :chunk_size => DEFAULT_CHUNK_SIZE,
        :checkpoint_every_chunks => DEFAULT_CHECKPOINT_EVERY_CHUNKS,
    )
    i = 1
    while i <= length(args)
        arg = args[i]
        if arg == "--help" || arg == "-h"
            print_help()
            exit(0)
        end
        arg in (
            "--start",
            "--final",
            "--skip-snapshots",
            "--chunk-size",
            "--checkpoint-every-chunks",
        ) || error("Unknown argument: $arg. Use --help.")
        i == length(args) && error("Missing value after $arg.")
        value = args[i + 1]
        if arg == "--start"
            settings[:start] = parse(Int, value)
        elseif arg == "--final"
            settings[:final] = lowercase(value) == "all" ? nothing : parse(Int, value)
        elseif arg == "--skip-snapshots"
            settings[:skip_snapshots] = parse(Int, value)
        elseif arg == "--chunk-size"
            settings[:chunk_size] = parse(Int, value)
        elseif arg == "--checkpoint-every-chunks"
            settings[:checkpoint_every_chunks] = parse(Int, value)
        end
        i += 2
    end
    settings[:start] >= 1 || error("--start must be >= 1.")
    if !isnothing(settings[:final])
        settings[:final] >= settings[:start] ||
            error("--final must be >= --start.")
    end
    settings[:skip_snapshots] >= 0 ||
        error("--skip-snapshots must be >= 0.")
    settings[:chunk_size] >= 1 ||
        error("--chunk-size must be >= 1.")
    settings[:checkpoint_every_chunks] >= 1 ||
        error("--checkpoint-every-chunks must be >= 1.")
    return settings
end

