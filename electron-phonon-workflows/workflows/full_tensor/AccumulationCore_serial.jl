# Periodic displacements
# -----------------------------------------------------------------------------
const IMAGE_OFFSETS = [
    (i, j, k) for i in -1:1 for j in -1:1 for k in -1:1
]
"""
Return Cartesian displacements `current - equilibrium`, using the shortest
periodic image in the (possibly non-orthogonal) supercell.
"""
function minimum_image_displacements(
    current_fractional::Matrix{Float64},
    equilibrium_fractional::Matrix{Float64},
    lattice::Matrix{Float64},
)
    size(current_fractional) == size(equilibrium_fractional) ||
        error("Current and equilibrium structures have different atom counts.")
    natoms = size(current_fractional, 2)
    displacements = zeros(Float64, 3, natoms)
    for atom in 1:natoms
        delta_fractional = current_fractional[:, atom] -
                           equilibrium_fractional[:, atom]
        nearest_integer = round.(Int, delta_fractional)
        best_norm2 = Inf
        best_cartesian = zeros(Float64, 3)
        for offset in IMAGE_OFFSETS
            image_shift = nearest_integer .+ collect(offset)
            candidate_fractional = delta_fractional .- image_shift
            candidate_cartesian = lattice * candidate_fractional
            candidate_norm2 = dot(candidate_cartesian, candidate_cartesian)
            if candidate_norm2 < best_norm2
                best_norm2 = candidate_norm2
                best_cartesian .= candidate_cartesian
            end
        end
        displacements[:, atom] .= best_cartesian
    end
    return displacements
end

# -----------------------------------------------------------------------------
# Accumulation in a shared sparse electronic pattern
# -----------------------------------------------------------------------------
mutable struct UHAccumulator
    dim::Int
    natoms::Int
    count::Int
    snapshot_indices::Vector{Int}
    xdatcar_marker_labels::Vector{Int}
    sum_u::Vector{Float64}  # order: x,y,z of atom 1; x,y,z of atom 2; ...
    sum_H::Dict{Tuple{Int, Int}, ComplexF64}
    sum_uH::Dict{Tuple{Int, Int}, Vector{ComplexF64}}
end
function UHAccumulator(dim::Int, natoms::Int)
    return UHAccumulator(
        dim,
        natoms,
        0,
        Int[],
        Int[],
        zeros(Float64, 3 * natoms),
        Dict{Tuple{Int, Int}, ComplexF64}(),
        Dict{Tuple{Int, Int}, Vector{ComplexF64}}(),
    )
end
"""
Accumulate
    sum_H[i,j]              += H[i,j]
    sum_u[d]                += u[d]
    sum_uH[d,i,j]           += u[d] * H[i,j]
for one snapshot. Here `d = (atom, Cartesian component)`.
"""
function accumulate_snapshot!(
    accumulator::UHAccumulator,
    H::SparseMatrixCSC{ComplexF64, Int},
    displacements::Matrix{Float64},
    snapshot_index::Int,
    marker_label::Int;
    tolerance::Float64=0.0,
)
    size(H) == (accumulator.dim, accumulator.dim) ||
        error("Hamiltonian dimensions changed between snapshots.")
    size(displacements) == (3, accumulator.natoms) ||
        error("Displacement array has an unexpected shape.")
    snapshot_index in accumulator.snapshot_indices &&
        error("Snapshot $snapshot_index has already been accumulated.")
    u = vec(displacements)
    accumulator.sum_u .+= u
    for column in 1:accumulator.dim
        for pointer in H.colptr[column]:(H.colptr[column + 1] - 1)
            row = H.rowval[pointer]
            value = H.nzval[pointer]
            abs(value) > tolerance || continue
            key = (row, column)
            weighted_sum = get!(accumulator.sum_uH, key) do
                zeros(ComplexF64, 3 * accumulator.natoms)
            end
            sum_H_before = get(accumulator.sum_H, key, 0.0 + 0.0im)
            accumulator.sum_H[key] = sum_H_before + value
            @inbounds for dof in eachindex(u)
                weighted_sum[dof] += u[dof] * value
            end
        end
    end
    accumulator.count += 1
    push!(accumulator.snapshot_indices, snapshot_index)
    push!(accumulator.xdatcar_marker_labels, marker_label)
    return accumulator
end
# The monitor retains the last M sparse Hamiltonians and displacements only.
# It reconstructs the earlier raw sums one electronic entry at a time.
# No second B / uH tensor and no temporary correlation-prefix HDF5 file.
const CONVERGENCE_LOG_FILE = joinpath(RUN_DIR, "uH_convergence.txt")

function start_convergence_log(; fresh::Bool, saved_count::Int)
    rows = Dict{Int,Vector{String}}()
    if !fresh && isfile(CONVERGENCE_LOG_FILE)
        for line in eachline(CONVERGENCE_LOG_FILE)
            stripped = strip(line)
            (isempty(stripped) || startswith(stripped, "#")) && continue
            fields = String.(split(stripped))
            length(fields) == 9 || continue
            n = tryparse(Int, fields[1])
            isnothing(n) && continue
            # Discard only rows newer than the successfully saved checkpoint.
            n <= saved_count || continue
            rows[n] = fields
        end
    end
    temporary = CONVERGENCE_LOG_FILE * ".tmp"
    open(temporary, "w") do io
        println(io, "# B_N = <uH>_N - <u>_N<H>_N, using ALL N accumulated snapshots.")
        println(io, "# At each HAMSTER chunk end, N=P+M; M is its last CONVERGENCE_M snapshots (or the entire chunk if shorter).")
        println(io, "# relative_change_B_norm preserves the scalar-norm change since the previous logged HAMSTER chunk end.")
        println(io, "# r_cumulative = ||B_(P+M)-B_P||_F/max(||B_(P+M)||_F,||B_P||_F). Each B uses its own means.")
        println(io, "# N_added=M and N_previous=P refer to r_cumulative; retained historical rows keep their original M and P.")
        println(io, "# Both relative quantities are dimensionless stability measures, not statistical error bars. NaN means no reference or zero denominator.")
        println(io, "# N_snapshots last_frame B_norm_eV_A B_rms_eV_A B_max_abs_eV_A relative_change_B_norm r_cumulative N_added N_previous")
        for n in sort!(collect(keys(rows)))
            println(io, join(rows[n], "  "))
        end
    end
    mv(temporary, CONVERGENCE_LOG_FILE; force=true)
    # Restore the old scalar monitor reference across a restart.
    return haskey(rows, saved_count) ? parse(Float64,rows[saved_count][3]) : nothing
end

# Only needed when a resumed checkpoint has no matching text-log row.
function cumulative_B_norm(accumulator::UHAccumulator)
    N = accumulator.count
    N > 0 || return nothing
    mean_u = accumulator.sum_u ./ N
    norm2 = 0.0
    for (key, sum_uH) in accumulator.sum_uH
        mean_H = get(accumulator.sum_H,key,0.0+0.0im)/N
        @inbounds for d in eachindex(mean_u)
            norm2 += abs2(sum_uH[d]/N - mean_u[d]*mean_H)
        end
    end
    return sqrt(norm2)
end

function append_convergence_log!(accumulator::UHAccumulator,
                                 monitored_H::Vector{SparseMatrixCSC{ComplexF64,Int}},
                                 monitored_u::Matrix{Float64},
                                 previous_logged_norm)
    N = accumulator.count
    M = length(monitored_H)
    P = N-M
    M > 0 || error("Cannot monitor an empty update.")
    size(monitored_u,2) == M || error("Monitor snapshot counts disagree.")
    mean_u_new = accumulator.sum_u ./ N
    delta_u = vec(sum(monitored_u; dims=2))
    mean_u_old = P > 0 ? (accumulator.sum_u .- delta_u) ./ P : zeros(length(delta_u))
    # Reuse these small buffers for every electronic entry.
    h_values = zeros(ComplexF64,M)
    delta_uH = M > 1 ? zeros(ComplexF64,length(delta_u)) : ComplexF64[]
    new_norm2 = 0.0
    old_norm2 = 0.0
    difference_norm2 = 0.0
    max_abs = 0.0
    components = 0
    # Include the entire stored union, including entries absent in the last M
    # snapshots: their normalization and centered values still change.
    for (key, sum_uH_new) in accumulator.sum_uH
        delta_H = 0.0+0.0im
        for t in 1:M
            value = monitored_H[t][key[1],key[2]]
            value = abs(value) > H_TOLERANCE ? value : 0.0+0.0im
            h_values[t] = value
            delta_H += value
        end
        sum_H_new = get(accumulator.sum_H,key,0.0+0.0im)
        mean_H_new = sum_H_new/N
        mean_H_old = P > 0 ? (sum_H_new-delta_H)/P : 0.0+0.0im
        if M > 1 && P > 0
            fill!(delta_uH,0.0+0.0im)
            for t in 1:M
                value = h_values[t]
                iszero(value) && continue
                @inbounds for d in eachindex(delta_uH)
                    delta_uH[d] += monitored_u[d,t]*value
                end
            end
        end
        @inbounds for d in eachindex(mean_u_new)
            b_new = sum_uH_new[d]/N - mean_u_new[d]*mean_H_new
            new_norm2 += abs2(b_new)
            max_abs = max(max_abs,abs(b_new))
            if P > 0
                # Recover S_uH(P) from S_uH(P+M), without storing B_P.
                added_uH = M == 1 ? monitored_u[d,1]*h_values[1] : delta_uH[d]
                b_old = (sum_uH_new[d]-added_uH)/P - mean_u_old[d]*mean_H_old
                old_norm2 += abs2(b_old)
                difference_norm2 += abs2(b_new-b_old)
            end
        end
        components += length(mean_u_new)
    end
    new_norm = sqrt(new_norm2)
    old_norm = sqrt(old_norm2)
    denominator = max(new_norm,old_norm)
    r_cumulative = P > 0 && denominator > 0 ? sqrt(difference_norm2)/denominator : NaN
    # Preserve the original norm-only comparison between logged chunk ends.
    relative_change = if isnothing(previous_logged_norm)
        NaN
    else
        scalar_denominator = max(new_norm,previous_logged_norm)
        scalar_denominator > 0 ? abs(new_norm-previous_logged_norm)/scalar_denominator : NaN
    end
    rms = components > 0 ? new_norm/sqrt(components) : NaN
    open(CONVERGENCE_LOG_FILE,"a") do io
        @printf(io,"%d  %d  %.12e  %.12e  %.12e  %.12e  %.12e  %d  %d\n",
            N,last(accumulator.snapshot_indices),new_norm,rms,max_abs,
            relative_change,r_cumulative,M,P)
    end
    return new_norm
end

function sorted_electronic_keys(accumulator::UHAccumulator)
    keys_union = union(keys(accumulator.sum_H), keys(accumulator.sum_uH))
    return sort(collect(keys_union); by=key -> (key[2], key[1]))
end
"""
Load a previous checkpoint and reconstruct the running sums.
Format version 3 stores means to avoid duplicating the very large `uH` array.
The exact running sums are reconstructed as `mean * number_of_snapshots`.
Older format version 2 files, which stored explicit sums, are also accepted.
"""
# Stream the large uH tensor between HDF5 and its existing column dictionary.
# Extra working storage is limited to CHECKPOINT_COLUMN_BLOCK_SIZE columns.
function restore_uH_columns!(accumulator::UHAccumulator, dataset, orbital_i,
                             orbital_j, multiplier::Real)
    ndof = 3 * accumulator.natoms
    nentries = length(orbital_i)
    size(dataset) == (ndof, nentries) ||
        error("Checkpoint uH has shape $(size(dataset)); expected ($ndof, $nentries).")
    CHECKPOINT_COLUMN_BLOCK_SIZE > 0 || error("CHECKPOINT_COLUMN_BLOCK_SIZE must be positive.")
    for first_column in 1:CHECKPOINT_COLUMN_BLOCK_SIZE:nentries
        last_column = min(first_column + CHECKPOINT_COLUMN_BLOCK_SIZE - 1, nentries)
        # Read only this slab, never the complete matrix.
        slab = dataset[:, first_column:last_column]
        for entry in first_column:last_column
            local_column = entry - first_column + 1
            values = Vector{ComplexF64}(undef, ndof)
            @inbounds for d in 1:ndof
                values[d] = multiplier * slab[d, local_column]
            end
            accumulator.sum_uH[(orbital_i[entry], orbital_j[entry])] = values
        end
    end
    return nothing
end

function write_mean_uH_columns!(group, accumulator::UHAccumulator, keys_sorted)
    ndof = 3 * accumulator.natoms
    nentries = length(keys_sorted)
    CHECKPOINT_COLUMN_BLOCK_SIZE > 0 || error("CHECKPOINT_COLUMN_BLOCK_SIZE must be positive.")
    dtype = datatype(ComplexF64)
    space = dataspace((ndof, nentries))
    dataset = nothing
    try
        # Dataset names, shape, complex type and normalization are unchanged.
        dataset = create_dataset(group, "mean_uH_eV_angstrom", dtype, space)
        width = min(CHECKPOINT_COLUMN_BLOCK_SIZE, nentries)
        buffer = Matrix{ComplexF64}(undef, ndof, width)
        inverse_count = 1.0 / accumulator.count
        for first_column in 1:CHECKPOINT_COLUMN_BLOCK_SIZE:nentries
            last_column = min(first_column + CHECKPOINT_COLUMN_BLOCK_SIZE - 1, nentries)
            ncolumns = last_column - first_column + 1
            if size(buffer, 2) != ncolumns
                # Only the final partial slab needs a smaller buffer.
                buffer = Matrix{ComplexF64}(undef, ndof, ncolumns)
            end
            fill!(buffer, 0.0 + 0.0im)
            for entry in first_column:last_column
                key = keys_sorted[entry]
                source = get(accumulator.sum_uH, key, nothing)
                source === nothing && continue
                local_column = entry - first_column + 1
                @inbounds for d in 1:ndof
                    buffer[d, local_column] = source[d] * inverse_count
                end
            end
            # Buffer is a normal Array, avoiding a copy of a view by HDF5.jl.
            dataset[:, first_column:last_column] = buffer
        end
    finally
        dataset !== nothing && close(dataset)
        close(space)
        close(dtype)
    end
    return nothing
end

function load_existing_accumulator(filename::AbstractString)::UHAccumulator
    isfile(filename) || error("Checkpoint does not exist: $filename")
    return h5open(filename, "r") do f
        format_version = haskey(f, "format_version") ? Int(read(f["format_version"])) : 1
        count = Int(read(f["number_of_snapshots"]))
        dim = Int(read(f["hamiltonian_dimension"]))
        natoms = Int(read(f["number_of_atoms"]))
        snapshot_indices = Vector{Int}(read(f["snapshot_indices"]))
        marker_labels = Vector{Int}(read(f["xdatcar_marker_labels"]))
        count == length(snapshot_indices) ||
            error("Checkpoint snapshot count does not match snapshot_indices length.")
        count == length(marker_labels) ||
            error("Checkpoint snapshot count does not match marker-label length.")
        length(unique(snapshot_indices)) == length(snapshot_indices) ||
            error("Checkpoint contains duplicate processed snapshot indices.")
        orbital_i = Vector{Int}(read(f["electronic/matrix_row_i"]))
        orbital_j = Vector{Int}(read(f["electronic/matrix_column_j"]))
        length(orbital_i) == length(orbital_j) ||
            error("Checkpoint electronic row/column arrays have different lengths.")
        nentries = length(orbital_i)
        ndof = 3 * natoms
        accumulator = UHAccumulator(dim, natoms)
        accumulator.count = count
        accumulator.snapshot_indices = snapshot_indices
        accumulator.xdatcar_marker_labels = marker_labels
        if format_version >= 3 && haskey(f, "accumulators/mean_H_eV")
            mean_u = Vector{Float64}(read(f["accumulators/mean_u_angstrom"]))
            mean_H = ComplexF64.(vec(read(f["accumulators/mean_H_eV"])))
            mean_uH_dataset = f["accumulators/mean_uH_eV_angstrom"]
            length(mean_u) == ndof || error("Checkpoint mean_u has wrong length.")
            length(mean_H) == nentries || error("Checkpoint mean_H has wrong length.")

            accumulator.sum_u .= count .* mean_u
            for entry in 1:nentries
                key = (orbital_i[entry], orbital_j[entry])
                accumulator.sum_H[key] = count * mean_H[entry]
            end
            try
                restore_uH_columns!(accumulator, mean_uH_dataset, orbital_i, orbital_j, count)
            finally
                close(mean_uH_dataset)
            end
        elseif haskey(f, "accumulators/sum_H")
            # Backward compatibility with the previous code.
            sum_u = Vector{Float64}(read(f["accumulators/sum_u_angstrom"]))
            sum_H = ComplexF64.(vec(read(f["accumulators/sum_H"])))
            sum_uH_dataset = f["accumulators/sum_uH_eV_angstrom"]
            length(sum_u) == ndof || error("Checkpoint sum_u has wrong length.")
            length(sum_H) == nentries || error("Checkpoint sum_H has wrong length.")

            accumulator.sum_u .= sum_u
            for entry in 1:nentries
                key = (orbital_i[entry], orbital_j[entry])
                accumulator.sum_H[key] = sum_H[entry]
            end
            try
                restore_uH_columns!(accumulator, sum_uH_dataset, orbital_i, orbital_j, 1.0)
            finally
                close(sum_uH_dataset)
            end
        else
            error(
                "Checkpoint does not contain recognised accumulator datasets " *
                "(format version $format_version)."
            )
        end
        return accumulator
    end
end
function validate_resumed_accumulator!(
    accumulator::UHAccumulator,
    target_snapshot_indices::Vector{Int},
    equilibrium::VaspStructure,
)
    accumulator.natoms == length(equilibrium.header.atom_species) ||
        error("Checkpoint atom count differs from POSCAR_equlibr.")
    target = Set(target_snapshot_indices)
    invalid_processed = sort([
        index for index in accumulator.snapshot_indices if !(index in target)
    ])
    isempty(invalid_processed) ||
        error(
            "Checkpoint contains snapshot(s) outside the currently requested " *
            "selection: $(join(invalid_processed, ", ")). " *
            "Use EXISTING_OUTPUT_MODE=:overwrite or restore the original selection."
        )
    return accumulator
end
function validate_checkpoint_target_selection!(
    filename::AbstractString,
    target_snapshot_indices::Vector{Int},
)
    isfile(filename) || return nothing
    h5open(filename, "r") do f
        if haskey(f, "progress/available_snapshot_indices")
            stored = Vector{Int}(read(f["progress/available_snapshot_indices"]))
            stored == target_snapshot_indices || error(
                "The existing checkpoint was created for a different snapshot " *
                "selection. Current selection has $(length(target_snapshot_indices)) " *
                "snapshot(s), from $(first(target_snapshot_indices)) to " *
                "$(last(target_snapshot_indices)). Use :overwrite if this change " *
                "is intentional."
            )
        end
    end
    return nothing
end
"""Write an atomic checkpoint: first to a temporary file, then rename it."""
function write_checkpoint(
    filename::AbstractString,
    accumulator::UHAccumulator,
    equilibrium::VaspStructure,
    xdatcar_header::VaspHeader,
    basis,
    basis_key,
    ham_file::AbstractString,
    xdatcar_file::AbstractString,
    equilibrium_file::AbstractString,
    primitive_file::AbstractString,
    hconf_file::AbstractString,
    primitive_mapping::PrimitiveBasisMap,
    all_snapshot_indices::Vector{Int},
)
    accumulator.count > 0 || error("Cannot write an empty accumulator.")
    keys_sorted = sorted_electronic_keys(accumulator)
    nentries = length(keys_sorted)
    ndof = 3 * accumulator.natoms
    orbital_i = Vector{Int}(undef, nentries)
    orbital_j = Vector{Int}(undef, nentries)
    mean_H_values = zeros(ComplexF64, nentries)
    inverse_count = 1.0 / accumulator.count
    for (entry, key) in enumerate(keys_sorted)
        orbital_i[entry], orbital_j[entry] = key
        mean_H_values[entry] = get(accumulator.sum_H, key, 0.0 + 0.0im) * inverse_count
    end
    mean_u = accumulator.sum_u .* inverse_count
    dof_atom = repeat(collect(1:accumulator.natoms); inner=3)
    dof_component = repeat(["x", "y", "z"], accumulator.natoms)
    processed_set = Set(accumulator.snapshot_indices)
    remaining_snapshot_indices = [
        index for index in all_snapshot_indices if !(index in processed_set)
    ]
    temporary = filename * ".tmp"
    isfile(temporary) && rm(temporary; force=true)
    h5open(temporary, "w") do f
        f["format_version"] = 3
        f["number_of_snapshots"] = accumulator.count
        f["snapshot_indices"] = accumulator.snapshot_indices
        f["xdatcar_marker_labels"] = accumulator.xdatcar_marker_labels
        f["hamiltonian_dimension"] = accumulator.dim
        f["number_of_atoms"] = accumulator.natoms
        progress = create_group(f, "progress")
        progress["available_snapshot_indices"] = all_snapshot_indices
        progress["processed_snapshot_indices"] = accumulator.snapshot_indices
        progress["remaining_snapshot_indices"] = remaining_snapshot_indices
        progress["last_processed_snapshot_index"] = last(accumulator.snapshot_indices)
        progress["is_complete"] = isempty(remaining_snapshot_indices)
        sources = create_group(f, "sources")
        sources["temporary_chunk_hamiltonian_file"] = abspath(ham_file)
        sources["xdatcar_file"] = abspath(xdatcar_file)
        sources["equilibrium_poscar"] = abspath(equilibrium_file)
        sources["primitive_poscar"] = abspath(primitive_file)
        sources["hamster_config_template"] = abspath(hconf_file)
        sources["hamiltonian_generation_mode"] = "temporary HAMSTER chunks"
        geometry = create_group(f, "geometry")
        geometry["lattice_angstrom"] = equilibrium.header.lattice
        geometry["equilibrium_fractional_positions"] =
            equilibrium.fractional_positions
        geometry["atom_species"] = equilibrium.header.atom_species
        geometry["xdatcar_lattice_angstrom"] = xdatcar_header.lattice
        electronic = create_group(f, "electronic")
        electronic["matrix_row_i"] = orbital_i
        electronic["matrix_column_j"] = orbital_j
        row_addresses = [
            relabel_basis_index(primitive_mapping, i) for i in orbital_i
        ]
        column_addresses = [
            relabel_basis_index(primitive_mapping, j) for j in orbital_j
        ]
        electronic["mu"] = [a.primitive_orbital for a in row_addresses]
        electronic["R"] = hcat([collect(a.cell) for a in row_addresses]...)
        electronic["mu_primitive_atom"] = [a.primitive_atom for a in row_addresses]
        electronic["mu_local_orbital"] = [a.local_orbital for a in row_addresses]
        electronic["mu_orbital_token"] = [a.orbital_token for a in row_addresses]
        electronic["mu_basis_label"] = [a.basis_label for a in row_addresses]
        electronic["mu_spin_slot"] = [a.spin_slot for a in row_addresses]
        electronic["nu"] = [a.primitive_orbital for a in column_addresses]
        electronic["Rprime"] = hcat([collect(a.cell) for a in column_addresses]...)
        electronic["nu_primitive_atom"] = [a.primitive_atom for a in column_addresses]
        electronic["nu_local_orbital"] = [a.local_orbital for a in column_addresses]
        electronic["nu_orbital_token"] = [a.orbital_token for a in column_addresses]
        electronic["nu_basis_label"] = [a.basis_label for a in column_addresses]
        electronic["nu_spin_slot"] = [a.spin_slot for a in column_addresses]
        if !isnothing(basis)
            electronic["hamster_basis"] = basis
        end
        if !isnothing(basis_key)
            electronic["basis_source_dataset"] = String(basis_key)
        end
        mapping_group = create_group(f, "primitive_basis_mapping")
        mapping_table = primitive_basis_mapping_table(primitive_mapping)
        mapping_group["basis_index"] = mapping_table.basis_index
        mapping_group["supercell_atom"] = mapping_table.supercell_atom
        mapping_group["primitive_orbital_mu"] = mapping_table.primitive_orbital
        mapping_group["primitive_atom"] = mapping_table.primitive_atom
        mapping_group["local_orbital"] = mapping_table.local_orbital
        mapping_group["orbital_token"] = mapping_table.orbital_token
        mapping_group["basis_label"] = mapping_table.basis_label
        mapping_group["spin_slot"] = mapping_table.spin_slot
        mapping_group["cell_R"] = mapping_table.cell
        mapping_group["repetitions_n1_n2_n3"] = collect(primitive_mapping.repetitions)
        mapping_group["supercell_matrix"] = primitive_mapping.supercell_matrix
        mapping_group["number_of_primitive_cells"] = primitive_mapping.number_of_primitive_cells
        accumulators = create_group(f, "accumulators")
        accumulators["dof_supercell_atom"] = dof_atom
        accumulators["dof_component"] = dof_component
        accumulators["dof_primitive_atom_alpha"] = [
            primitive_mapping.atom_to_primitive_atom[atom] for atom in dof_atom
        ]
        accumulators["dof_cell_L"] = hcat([
            collect(primitive_mapping.atom_to_cell[atom]) for atom in dof_atom
        ]...)
        # These are the actual trajectory averages exposed to later analysis.
        # The restart state is reconstructed from mean * number_of_snapshots.
        accumulators["mean_u_angstrom"] = mean_u
        accumulators["mean_H_eV"] = mean_H_values
        write_mean_uH_columns!(accumulators, accumulator, keys_sorted)
    end
    mv(temporary, filename; force=true)
    return nothing
end

# -----------------------------------------------------------------------------
# XDATCAR random-access index
# -----------------------------------------------------------------------------
struct XdatcarIndex
    header::VaspHeader
    frame_offsets::Vector{Int64}
    marker_labels::Vector{Int}
    direct_modes::BitVector
end
"""
Scan XDATCAR once and record the byte offset of every configuration marker.
Only O(number_of_frames) integers are stored. Later chunks can therefore read
their selected coordinates directly without rescanning the trajectory from
frame 1 every time.
"""
function build_xdatcar_index(filename::AbstractString)::XdatcarIndex
    isfile(filename) || error("XDATCAR does not exist: $filename")
    return open(filename, "r") do io
        header = read_vasp_header(io)
        natoms = sum(header.counts)
        offsets = Int64[]
        marker_labels = Int[]
        direct_modes = BitVector()
        frame_index = 0
        while !eof(io)
            marker_offset = position(io)
            marker_line = strip(readline(io))
            isempty(marker_line) && continue
            marker_lower = lowercase(marker_line)
            is_direct = startswith(marker_lower, "direct")
            is_cartesian = startswith(marker_lower, "cartesian") ||
                           startswith(marker_lower, "kpoints")
            (is_direct || is_cartesian) && occursin("configuration", marker_lower) ||
                error(
                    "Expected an XDATCAR configuration marker, found: " *
                    "\"$marker_line\"."
                )
            frame_index += 1
            marker_match = match(r"configuration\s*=\s*([0-9]+)", marker_lower)
            marker_label = isnothing(marker_match) ?
                           frame_index : parse(Int, marker_match.captures[1])
            push!(offsets, Int64(marker_offset))
            push!(marker_labels, marker_label)
            push!(direct_modes, is_direct)
            for atom in 1:natoms
                eof(io) && error("XDATCAR ended inside frame $frame_index.")
                readline(io)
            end
        end
        isempty(offsets) && error("No configurations were found in $filename.")
        return XdatcarIndex(header, offsets, marker_labels, direct_modes)
    end
end
function foreach_indexed_xdatcar_frame(
    callback::Function,
    filename::AbstractString,
    index::XdatcarIndex,
    wanted_indices::Vector{Int},
)
    isempty(wanted_indices) && return nothing
    nframes = length(index.frame_offsets)
    all(i -> 1 <= i <= nframes, wanted_indices) ||
        error("Requested XDATCAR frame outside 1:$nframes.")
    natoms = sum(index.header.counts)
    open(filename, "r") do io
        for frame_index in wanted_indices
            seek(io, index.frame_offsets[frame_index])
            marker_line = strip(readline(io))
            marker_lower = lowercase(marker_line)
            is_direct = index.direct_modes[frame_index]
            coordinates = zeros(Float64, 3, natoms)
            for atom in 1:natoms
                coordinates[:, atom] .= parse_float_triplet(readline(io))
            end
            fractional = if is_direct
                coordinates
            else
                cartesian = index.header.coordinate_scale .* coordinates
                index.header.lattice \ cartesian
            end
            callback(
                frame_index,
                index.marker_labels[frame_index],
                fractional,
                index.header,
            )
        end
    end
    return nothing
end

# -----------------------------------------------------------------------------
# Snapshot selection and chunking
# -----------------------------------------------------------------------------
function selected_snapshot_indices(settings, number_of_xdatcar_frames::Int)
    start_snapshot = settings[:start]
    final_snapshot = isnothing(settings[:final]) ?
                     number_of_xdatcar_frames : settings[:final]
    start_snapshot <= number_of_xdatcar_frames || error(
        "Requested start snapshot $start_snapshot, but XDATCAR contains only " *
        "$number_of_xdatcar_frames frame(s)."
    )
    final_snapshot <= number_of_xdatcar_frames || error(
        "Requested final snapshot $final_snapshot, but XDATCAR contains only " *
        "$number_of_xdatcar_frames frame(s)."
    )
    stride = settings[:skip_snapshots] + 1
    selected = collect(start_snapshot:stride:final_snapshot)
    isempty(selected) && error("The requested snapshot selection is empty.")
    return selected
end
function make_chunks(indices::Vector{Int}, chunk_size::Int)
    return [
        indices[i:min(i + chunk_size - 1, end)]
        for i in 1:chunk_size:length(indices)
    ]
end

# -----------------------------------------------------------------------------
# HAMSTER hconf rewriting
# -----------------------------------------------------------------------------
function active_tag(line::AbstractString)
    stripped = strip(line)
    isempty(stripped) && return nothing
    startswith(stripped, "#") && return nothing
    m = match(r"^([A-Za-z_][A-Za-z0-9_]*)\s*=", stripped)
    return isnothing(m) ? nothing : lowercase(m.captures[1])
end
"""
Create a temporary HAMSTER hconf for exactly one chunk.
The original hconf is never edited. In the temporary copy we set:
    Options:
        ham_file = CHUNK_HAM_FILE
    Supercell:
        Nconf      = length(chunk_indices)
        Nconf_min  = minimum(chunk_indices)
        Nconf_max  = maximum(chunk_indices)
        config_inds = <exact list>
`config_inds` is always written, even for a contiguous chunk. This guarantees
that HAMSTER evaluates exactly the requested snapshots and is essential when
SKIP_SNAPSHOTS > 0.
"""
function write_chunk_hconf(
    template_file::AbstractString,
    output_file::AbstractString,
    chunk_ham_file::AbstractString,
    chunk_indices::Vector{Int},
)
    isfile(template_file) || error("HAMSTER hconf does not exist: $template_file")
    isempty(chunk_indices) && error("Cannot create an empty HAMSTER chunk.")
    lines = readlines(template_file)
    output = String[]
    current_block = nothing
    found_options = false
    found_supercell = false
    seen_ham_file = false
    seen_nconf = false
    seen_nconf_min = false
    seen_nconf_max = false
    seen_config_inds = false
    nconf = length(chunk_indices)
    nconf_min = minimum(chunk_indices)
    nconf_max = maximum(chunk_indices)
    config_inds_line = "    config_inds = " * join(chunk_indices, " ")
    for line in lines
        stripped = strip(line)
        begin_match = match(r"^begin\s+([A-Za-z_][A-Za-z0-9_]*)\s*$"i, stripped)
        if !isnothing(begin_match)
            current_block = lowercase(begin_match.captures[1])
            found_options |= current_block == "options"
            found_supercell |= current_block == "supercell"
            push!(output, line)
            continue
        end
        if lowercase(stripped) == "end" && !isnothing(current_block)
            if current_block == "options" && !seen_ham_file
                push!(output, "    ham_file = $(abspath(chunk_ham_file))")
                seen_ham_file = true
            elseif current_block == "supercell"
                if !seen_nconf
                    push!(output, "    Nconf = $nconf")
                    seen_nconf = true
                end
                if !seen_nconf_min
                    push!(output, "    Nconf_min = $nconf_min")
                    seen_nconf_min = true
                end
                if !seen_nconf_max
                    push!(output, "    Nconf_max = $nconf_max")
                    seen_nconf_max = true
                end
                if !seen_config_inds
                    push!(output, config_inds_line)
                    seen_config_inds = true
                end
            end
            push!(output, line)
            current_block = nothing
            continue
        end
        tag = active_tag(line)
        if current_block == "options" && tag == "ham_file"
            push!(output, "    ham_file = $(abspath(chunk_ham_file))")
            seen_ham_file = true

        elseif current_block == "supercell" && tag == "xdatcar"
            push!(output, "    xdatcar = $(abspath(XDATCAR_FILE))")

        elseif current_block == "supercell" && tag == "nconf"
            push!(output, "    Nconf = $nconf")
            seen_nconf = true
        elseif current_block == "supercell" && tag == "nconf_min"
            push!(output, "    Nconf_min = $nconf_min")
            seen_nconf_min = true
        elseif current_block == "supercell" && tag == "nconf_max"
            push!(output, "    Nconf_max = $nconf_max")
            seen_nconf_max = true
        elseif current_block == "supercell" && tag == "config_inds"
            push!(output, config_inds_line)
            seen_config_inds = true
        else
            push!(output, line)
        end
    end
    found_options || error("No begin Options ... end block found in $template_file.")
    found_supercell || error("No begin Supercell ... end block found in $template_file.")
    seen_ham_file || error("Failed to set ham_file in temporary hconf.")
    seen_nconf || error("Failed to set Nconf in temporary hconf.")
    seen_nconf_min || error("Failed to set Nconf_min in temporary hconf.")
    seen_nconf_max || error("Failed to set Nconf_max in temporary hconf.")
    seen_config_inds || error("Failed to set config_inds in temporary hconf.")
    open(output_file, "w") do io
        for line in output
            println(io, line)
        end
    end
    return nothing
end

# -----------------------------------------------------------------------------
# HAMSTER chunk execution / validation
# -----------------------------------------------------------------------------
function select_available_snapshots(
    ham_file::AbstractString;
    system::Union{Nothing, AbstractString}=nothing,
)
    all_groups = available_hamster_snapshots(ham_file)
    trajectory_groups = filter(x -> x.snapshot_index > 0, all_groups)
    if !isnothing(system)
        trajectory_groups = filter(x -> x.system == String(system), trajectory_groups)
    else
        systems = unique(x.system for x in trajectory_groups)
        if length(systems) > 1
            error(
                "The Hamiltonian file contains several systems: " *
                "$(join(systems, ", ")). Set SYSTEM explicitly."
            )
        end
    end
    isempty(trajectory_groups) &&
        error("No trajectory real-space Hamiltonians were found in $ham_file.")
    sort!(trajectory_groups; by=x -> x.snapshot_index)
    return trajectory_groups
end
function run_hamster_chunk(chunk_indices::Vector{Int})
    isfile(CHUNK_HAM_FILE) && rm(CHUNK_HAM_FILE; force=true)
    isfile(CHUNK_HCONF_FILE) && rm(CHUNK_HCONF_FILE; force=true)
    write_chunk_hconf(
        HCONF_TEMPLATE_FILE,
        CHUNK_HCONF_FILE,
        CHUNK_HAM_FILE,
        chunk_indices,
    )
    progress_println(
        "Running HAMSTER for chunk: ",
        first(chunk_indices),
        " ... ",
        last(chunk_indices),
        "  (",
        length(chunk_indices),
        " selected snapshot(s))",
    )
    Main.run_hamster_parallel(CHUNK_HCONF_FILE)
    isfile(CHUNK_HAM_FILE) || error(
        "HAMSTER finished without creating the expected chunk file: $CHUNK_HAM_FILE"
    )
    groups = select_available_snapshots(CHUNK_HAM_FILE; system=SYSTEM)
    generated_indices = [x.snapshot_index for x in groups]
    generated_indices == chunk_indices || error(
        "HAMSTER chunk contains snapshot indices $(generated_indices), but the " *
        "driver requested $(chunk_indices). Check the Supercell/config_inds " *
        "handling in the generated hconf: $CHUNK_HCONF_FILE"
    )
    return groups
end

# -----------------------------------------------------------------------------
# Main calculation
# -----------------------------------------------------------------------------
function main()
    settings = parse_arguments(ARGS)
    1 <= CONVERGENCE_M <= settings[:chunk_size] ||
        error("CONVERGENCE_M must be between 1 and the HAMSTER chunk size.")
    EXISTING_OUTPUT_MODE in (:resume, :overwrite, :error) ||
        error("EXISTING_OUTPUT_MODE must be :resume, :overwrite, or :error.")
    for path in (
        XDATCAR_FILE,
        EQUILIBRIUM_POSCAR,
        PRIMITIVE_POSCAR,
        HCONF_TEMPLATE_FILE,
    )
        isfile(path) || error("Required input file does not exist: $path")
    end
    equilibrium = read_poscar(EQUILIBRIUM_POSCAR)
    # Scan the trajectory only once. Later coordinate reads use byte offsets.
    progress_println("Indexing XDATCAR...")
    xdatcar_index = build_xdatcar_index(XDATCAR_FILE)
    number_of_frames = length(xdatcar_index.frame_offsets)
    all_snapshot_indices =
        selected_snapshot_indices(settings, number_of_frames)
    progress_println("XDATCAR frames available: $number_of_frames")
    progress_println(
        "Selected Hamiltonian snapshots: $(length(all_snapshot_indices)); " *
        "first = $(first(all_snapshot_indices)), " *
        "last = $(last(all_snapshot_indices)), " *
        "skip_snapshots = $(settings[:skip_snapshots])"
    )
    progress_println(
        "Chunk size = $(settings[:chunk_size]); checkpoint every " *
        "$(settings[:checkpoint_every_chunks]) chunk(s)."
    )
    accumulator = nothing
    if isfile(OUTPUT_FILE)
        if EXISTING_OUTPUT_MODE == :error
            error(
                "Output file already exists: $OUTPUT_FILE. " *
                "Use EXISTING_OUTPUT_MODE=:resume or :overwrite."
            )
        elseif EXISTING_OUTPUT_MODE == :overwrite
            rm(OUTPUT_FILE; force=true)
            temporary = OUTPUT_FILE * ".tmp"
            isfile(temporary) && rm(temporary; force=true)
            progress_println("Removed previous accumulator; starting from scratch.")
        else
            validate_checkpoint_target_selection!(
                OUTPUT_FILE,
                all_snapshot_indices,
            )
            accumulator = load_existing_accumulator(OUTPUT_FILE)
            validate_resumed_accumulator!(
                accumulator,
                all_snapshot_indices,
                equilibrium,
            )
            progress_println(
                "Resuming from $OUTPUT_FILE with " *
                "$(accumulator.count) already processed snapshot(s)."
            )
        end
    end
    processed_indices = isnothing(accumulator) ?
                        Set{Int}() : Set(accumulator.snapshot_indices)
    remaining_snapshot_indices = [
        index for index in all_snapshot_indices if !(index in processed_indices)
    ]
    previous_logged_norm = start_convergence_log(fresh=isnothing(accumulator),
                          saved_count=isnothing(accumulator) ? 0 : accumulator.count)
    if isnothing(previous_logged_norm) && !isnothing(accumulator)
        previous_logged_norm = cumulative_B_norm(accumulator)
    end
    if isempty(remaining_snapshot_indices)
        progress_println("All requested snapshots have already been processed.")
        progress_println("Output: $OUTPUT_FILE")
        return nothing
    end
    chunks = make_chunks(
        remaining_snapshot_indices,
        settings[:chunk_size],
    )
    progress_println(
        "Remaining: $(length(remaining_snapshot_indices)) snapshot(s) in " *
        "$(length(chunks)) chunk(s)."
    )
    reference_basis = nothing
    reference_basis_key = nothing
    reference_xdatcar_header = xdatcar_index.header
    primitive_mapping = nothing
    chunks_since_checkpoint = 0
    for (chunk_number, chunk_indices) in enumerate(chunks)
        progress_println(
            "Chunk $chunk_number/$(length(chunks)): exact snapshot indices = " *
            join(chunk_indices, ", ")
        )
        phase_clock=time()
        run_hamster_chunk(chunk_indices)
        println("PHASE hamster ",time()-phase_clock);flush(stdout)
        phase_clock=time()
        M = min(CONVERGENCE_M,length(chunk_indices))
        first_monitored_frame = chunk_indices[end-M+1]
        monitored_H = SparseMatrixCSC{ComplexF64,Int}[]
        monitored_u = Matrix{Float64}(undef,3*length(equilibrium.header.atom_species),M)
        # Read only this chunk's XDATCAR frames and pair each one with the
        # Hamiltonian group carrying the same global XDATCAR frame index.
        foreach_indexed_xdatcar_frame(
            XDATCAR_FILE,
            xdatcar_index,
            chunk_indices,
        ) do frame_index, marker_label, fractional_positions, xdatcar_header
            natoms = length(equilibrium.header.atom_species)
            length(xdatcar_header.atom_species) == natoms ||
                error("XDATCAR and POSCAR_equlibr have different atom counts.")
            xdatcar_header.atom_species == equilibrium.header.atom_species ||
                error(
                    "XDATCAR and POSCAR_equlibr have different atom ordering/species."
                )
            isapprox(
                xdatcar_header.lattice,
                equilibrium.header.lattice;
                rtol=1.0e-8,
                atol=1.0e-8,
            ) || error(
                "XDATCAR and POSCAR_equlibr lattices differ. This implementation " *
                "assumes a fixed-cell trajectory."
            )
            snapshot = load_hamster_snapshot(
                CHUNK_HAM_FILE,
                frame_index;
                system=SYSTEM,
            )
            H = snapshot.H_supercell_pbc
            if isnothing(accumulator)
                accumulator = UHAccumulator(snapshot.dim, natoms)
            else
                snapshot.dim == accumulator.dim ||
                    error(
                        "Hamiltonian dimension at snapshot $frame_index differs " *
                        "from the persistent accumulator."
                    )
                accumulator.natoms == natoms ||
                    error("Atom count differs from the persistent accumulator.")
            end
            if isnothing(primitive_mapping)
                reference_basis = snapshot.basis
                reference_basis_key = snapshot.basis_key
                primitive_mapping = build_primitive_basis_map(
                    PRIMITIVE_POSCAR,
                    EQUILIBRIUM_POSCAR,
                    HCONF_TEMPLATE_FILE,
                    reference_basis,
                    snapshot.dim;
                    lattice_tolerance=BASIS_LATTICE_TOLERANCE,
                    position_tolerance_angstrom=
                        BASIS_POSITION_TOLERANCE_ANGSTROM,
                )
            else
                snapshot.basis == reference_basis ||
                    error("Hamiltonian basis changed at snapshot $frame_index.")
            end
            displacements = minimum_image_displacements(
                fractional_positions,
                equilibrium.fractional_positions,
                equilibrium.header.lattice,
            )
            accumulate_snapshot!(
                accumulator,
                H,
                displacements,
                frame_index,
                marker_label;
                tolerance=H_TOLERANCE,
            )
            if frame_index >= first_monitored_frame
                # Retain references to the existing sparse matrices, not copies.
                push!(monitored_H,H)
                monitored_u[:,length(monitored_H)] = vec(displacements)
            end
        end

        println("PHASE correlation ",time()-phase_clock);flush(stdout)
        chunks_since_checkpoint += 1
        is_final_chunk = chunk_number == length(chunks)
        phase_clock=time()
        previous_logged_norm = append_convergence_log!(
            accumulator,monitored_H,monitored_u,previous_logged_norm)
        println("PHASE convergence ",time()-phase_clock);flush(stdout)
        # Release sparse snapshot references before writing a checkpoint.
        empty!(monitored_H)
        should_checkpoint =
            chunks_since_checkpoint >= settings[:checkpoint_every_chunks] ||
            is_final_chunk
        if should_checkpoint
            phase_clock=time()
            write_checkpoint(
                OUTPUT_FILE,
                accumulator,
                equilibrium,
                reference_xdatcar_header,
                reference_basis,
                reference_basis_key,
                CHUNK_HAM_FILE,
                XDATCAR_FILE,
                EQUILIBRIUM_POSCAR,
                PRIMITIVE_POSCAR,
                HCONF_TEMPLATE_FILE,
                primitive_mapping,
                all_snapshot_indices,
            )
            progress_println(
                "Checkpoint written after $(accumulator.count) total snapshot(s)."
            )
            println("PHASE checkpoint ",time()-phase_clock);flush(stdout)
            chunks_since_checkpoint = 0
        end
        if DELETE_CHUNK_HAMILTONIAN && isfile(CHUNK_HAM_FILE)
            rm(CHUNK_HAM_FILE; force=true)
        end
        # The generated hconf is cheap; remove it after a successful chunk.
        isfile(CHUNK_HCONF_FILE) && rm(CHUNK_HCONF_FILE; force=true)
    end
    progress_println(
        "Finished. Accumulated $(accumulator.count) Hamiltonian snapshot(s)."
    )
    progress_println("Output: $OUTPUT_FILE")
    progress_println("Convergence log: $CONVERGENCE_LOG_FILE")
    return nothing
end

